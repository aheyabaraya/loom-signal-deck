create or replace function public.harne_reserve_chat_quota(
  p_member_code text,
  p_reserved_microusd bigint
)
returns table (
  ok boolean,
  code text,
  thread_id uuid,
  ballot_id bigint,
  member_message_count integer,
  user_message_count integer,
  global_reserved_microusd bigint
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_day date := timezone('Asia/Seoul', now())::date;
  v_ballot_id bigint;
  v_thread_id uuid;
  v_member_count integer;
  v_user_count integer;
  v_global_reserved bigint;
  v_global_limit bigint := 100000;
begin
  if v_user_id is null then
    return query select false, 'HARNE_AUTH_REQUIRED', null::uuid, null::bigint, 0, 0, 0::bigint;
    return;
  end if;

  select ballot.id
    into v_ballot_id
  from public.harne_vote_questions question
  join public.harne_vote_rounds round on round.id = question.round_id
  join public.harne_vote_ballots ballot on ballot.question_id = question.id
  where question.kind = 'member_identity'
    and question.subject_key = p_member_code
    and round.status = 'open'
    and ballot.user_id = v_user_id
  limit 1;

  if v_ballot_id is null then
    return query select false, 'CHAT_VOTE_REQUIRED', null::uuid, null::bigint, 0, 0, 0::bigint;
    return;
  end if;

  insert into public.harne_chat_threads (user_id, member_code, unlock_ballot_id)
  values (v_user_id, p_member_code, v_ballot_id)
  on conflict (user_id, member_code) do update
    set unlock_ballot_id = excluded.unlock_ballot_id
  returning id into v_thread_id;

  if v_thread_id is null then
    select thread.id into v_thread_id
    from public.harne_chat_threads thread
    where thread.user_id = v_user_id and thread.member_code = p_member_code;
  end if;

  insert into public.harne_chat_daily_usage (user_id, member_code, usage_day)
  values (v_user_id, p_member_code, v_day)
  on conflict (user_id, member_code, usage_day) do nothing;

  insert into public.harne_chat_global_daily_usage (usage_day)
  values (v_day)
  on conflict (usage_day) do nothing;

  select usage.user_message_count, usage.reserved_microusd
    into v_member_count, v_global_reserved
  from public.harne_chat_daily_usage usage
  where usage.user_id = v_user_id
    and usage.member_code = p_member_code
    and usage.usage_day = v_day
  for update;

  select global_usage.reserved_microusd
    into v_global_reserved
  from public.harne_chat_global_daily_usage global_usage
  where global_usage.usage_day = v_day
  for update;

  select coalesce(sum(usage.user_message_count), 0)::integer
    into v_user_count
  from public.harne_chat_daily_usage usage
  where usage.user_id = v_user_id and usage.usage_day = v_day;

  if v_member_count >= 15 then
    return query select false, 'CHAT_MEMBER_DAILY_LIMIT', v_thread_id, v_ballot_id, v_member_count, v_user_count, v_global_reserved;
    return;
  end if;

  if v_user_count >= 30 then
    return query select false, 'CHAT_USER_DAILY_LIMIT', v_thread_id, v_ballot_id, v_member_count, v_user_count, v_global_reserved;
    return;
  end if;

  if v_global_reserved + p_reserved_microusd > v_global_limit then
    return query select false, 'CHAT_GLOBAL_BUDGET_EXHAUSTED', v_thread_id, v_ballot_id, v_member_count, v_user_count, v_global_reserved;
    return;
  end if;

  update public.harne_chat_daily_usage
  set user_message_count = user_message_count + 1,
      reserved_microusd = reserved_microusd + p_reserved_microusd
  where user_id = v_user_id and member_code = p_member_code and usage_day = v_day;

  update public.harne_chat_global_daily_usage
  set reserved_microusd = reserved_microusd + p_reserved_microusd
  where usage_day = v_day;

  return query select true, 'OK', v_thread_id, v_ballot_id, v_member_count + 1, v_user_count + 1, v_global_reserved + p_reserved_microusd;
end;
$$;

