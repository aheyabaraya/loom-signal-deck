create or replace function public.harne_submit_vote(
  p_question_id bigint,
  p_option_id bigint,
  p_brief text default null
)
returns table (ballot_id bigint, question_id bigint, option_id bigint, updated_at timestamptz)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_round_status text;
  v_ballot public.harne_vote_ballots;
begin
  if v_user_id is null then
    raise exception using errcode = 'P0001', message = 'HARNE_AUTH_REQUIRED';
  end if;

  if p_brief is not null and char_length(p_brief) > 240 then
    raise exception using errcode = 'P0001', message = 'HARNE_BRIEF_TOO_LONG';
  end if;

  select round.status
    into v_round_status
  from public.harne_vote_questions question
  join public.harne_vote_rounds round on round.id = question.round_id
  where question.id = p_question_id;

  if v_round_status is distinct from 'open' then
    raise exception using errcode = 'P0001', message = 'HARNE_ROUND_CLOSED';
  end if;

  if not exists (
    select 1
    from public.harne_vote_options option
    where option.id = p_option_id
      and option.question_id = p_question_id
  ) then
    raise exception using errcode = 'P0001', message = 'HARNE_OPTION_INVALID';
  end if;

  insert into public.harne_vote_ballots (question_id, user_id, option_id, brief)
  values (p_question_id, v_user_id, p_option_id, nullif(trim(p_brief), ''))
  on conflict (question_id, user_id) do update
    set option_id = excluded.option_id,
        brief = excluded.brief,
        updated_at = now()
  returning * into v_ballot;

  return query select v_ballot.id, v_ballot.question_id, v_ballot.option_id, v_ballot.updated_at;
end;
$$;

