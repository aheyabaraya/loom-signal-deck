create or replace function public.harne_settle_chat_turn(
  p_thread_id uuid,
  p_user_content text,
  p_assistant_content text,
  p_input_tokens integer,
  p_output_tokens integer,
  p_actual_microusd bigint,
  p_reserved_microusd bigint
)
returns table (user_message_id uuid, assistant_message_id uuid)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_member_code text;
  v_user_message_id uuid;
  v_assistant_message_id uuid;
  v_day date := timezone('Asia/Seoul', now())::date;
begin
  select thread.member_code into v_member_code
  from public.harne_chat_threads thread
  where thread.id = p_thread_id and thread.user_id = v_user_id
  for update;

  if v_member_code is null then
    raise exception using errcode = 'P0001', message = 'HARNE_THREAD_NOT_FOUND';
  end if;

  insert into public.harne_chat_messages (thread_id, role, content, moderation_status)
  values (p_thread_id, 'user', p_user_content, 'approved')
  returning id into v_user_message_id;

  insert into public.harne_chat_messages (
    thread_id, role, content, moderation_status, input_tokens, output_tokens, cost_microusd
  )
  values (
    p_thread_id, 'assistant', p_assistant_content, 'approved', p_input_tokens, p_output_tokens, p_actual_microusd
  )
  returning id into v_assistant_message_id;

  update public.harne_chat_threads set last_message_at = now() where id = p_thread_id;

  update public.harne_chat_daily_usage
  set reserved_microusd = greatest(0, reserved_microusd - p_reserved_microusd),
      actual_microusd = actual_microusd + p_actual_microusd
  where user_id = v_user_id and member_code = v_member_code and usage_day = v_day;

  update public.harne_chat_global_daily_usage
  set reserved_microusd = greatest(0, reserved_microusd - p_reserved_microusd),
      actual_microusd = actual_microusd + p_actual_microusd
  where usage_day = v_day;

  return query select v_user_message_id, v_assistant_message_id;
end;
$$;

