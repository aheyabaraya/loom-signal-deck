grant execute on function public.loom_save_fan_profile(text, text, text, boolean, jsonb, text, text, text, text) to authenticated;

create or replace function public.loom_submit_business_inquiry(
  p_name text,
  p_email text,
  p_company text,
  p_inquiry_type text,
  p_goal text,
  p_timeline text,
  p_budget_band text,
  p_policy_version text
)
returns table (inquiry_id uuid, created_at timestamptz)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_inquiry public.loom_business_inquiries;
begin
  if v_user_id is null then
    raise exception using errcode = 'P0001', message = 'LOOM_AUTH_REQUIRED';
  end if;
  if char_length(trim(p_name)) not between 2 and 100
    or char_length(lower(trim(p_email))) not between 3 and 254
    or lower(trim(p_email)) !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    or (p_company is not null and char_length(trim(p_company)) > 120)
    or p_inquiry_type not in ('brand_film', 'fashion_content', 'beauty_content', 'ai_content_system', 'other')
    or char_length(trim(p_goal)) not between 20 and 1200
    or p_timeline not in ('exploring', 'within_1_month', 'within_3_months', 'later')
    or p_budget_band not in ('undecided', 'under_3m_krw', '3m_to_10m_krw', 'over_10m_krw')
    or p_policy_version !~ '^loom-privacy-[0-9]{4}-[0-9]{2}$' then
    raise exception using errcode = 'P0001', message = 'LOOM_INQUIRY_INVALID';
  end if;

  if 'granted' is distinct from (
    select consent.state
    from public.loom_marketing_consents consent
    where consent.user_id = v_user_id and consent.purpose = 'business_contact'
    order by consent.occurred_at desc
    limit 1
  ) then
    insert into public.loom_marketing_consents (user_id, purpose, state, policy_version)
    values (v_user_id, 'business_contact', 'granted', p_policy_version);
  end if;

  insert into public.loom_business_inquiries (
    user_id,
    name,
    email,
    company,
    inquiry_type,
    goal,
    timeline,
    budget_band,
    consent_policy_version
  ) values (
    v_user_id,
    trim(p_name),
    lower(trim(p_email)),
    nullif(trim(p_company), ''),
    p_inquiry_type,
    trim(p_goal),
    p_timeline,
    p_budget_band,
    p_policy_version
  )
  returning * into v_inquiry;

  return query select v_inquiry.id, v_inquiry.created_at;
end;
$$;

revoke all on function public.loom_submit_business_inquiry(text, text, text, text, text, text, text, text) from public, anon, authenticated;
grant execute on function public.loom_submit_business_inquiry(text, text, text, text, text, text, text, text) to authenticated;

create or replace function public.loom_marketing_summary(
  p_since timestamptz default (now() - interval '30 days')
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_events_total bigint;
  v_events_by_name jsonb;
  v_campaigns jsonb;
  v_inquiries jsonb;
  v_membership jsonb;
begin
  if not public.loom_is_staff() then
    raise exception using errcode = 'P0001', message = 'LOOM_STAFF_REQUIRED';
  end if;
  if p_since < now() - interval '365 days' or p_since > now() then
    raise exception using errcode = 'P0001', message = 'LOOM_SUMMARY_WINDOW_INVALID';
  end if;

  select count(*) into v_events_total
  from public.loom_marketing_events event
  where event.received_at >= p_since;

  select coalesce(jsonb_object_agg(summary.event_name, summary.event_count), '{}'::jsonb)
    into v_events_by_name
  from (
    select event.event_name, count(*)::bigint as event_count
    from public.loom_marketing_events event
    where event.received_at >= p_since
    group by event.event_name
  ) summary;

  select coalesce(jsonb_object_agg(summary.campaign_id, summary.event_count), '{}'::jsonb)
    into v_campaigns
  from (
    select event.campaign_id, count(*)::bigint as event_count
    from public.loom_marketing_events event
    where event.received_at >= p_since and event.campaign_id is not null
    group by event.campaign_id
  ) summary;

  select coalesce(jsonb_object_agg(summary.status, summary.inquiry_count), '{}'::jsonb)
    into v_inquiries
  from (
    select inquiry.status, count(*)::bigint as inquiry_count
    from public.loom_business_inquiries inquiry
    where inquiry.created_at >= p_since
    group by inquiry.status
  ) summary;

  select coalesce(jsonb_object_agg(summary.plan_key, summary.interest_count), '{}'::jsonb)
    into v_membership
  from (
    select interest.plan_key, count(*)::bigint as interest_count
    from public.loom_membership_interests interest
    where interest.state = 'interested'
    group by interest.plan_key
  ) summary;

  return jsonb_build_object(
    'windowStart', p_since,
    'generatedAt', now(),
    'eventsTotal', v_events_total,
    'eventsByName', v_events_by_name,
    'campaigns', v_campaigns,
    'inquiriesByStatus', v_inquiries,
    'membershipByPlan', v_membership
  );
end;
$$;

revoke all on function public.loom_marketing_summary(timestamptz) from public, anon, authenticated;
grant execute on function public.loom_marketing_summary(timestamptz) to authenticated;

