create or replace function public.loom_is_staff()
returns boolean
language sql
stable
security definer
set search_path = private, pg_temp
as $$
  select exists (
    select 1
    from private.loom_staff_users staff
    where staff.user_id = (select auth.uid())
  );
$$;

