create or replace function public.loom_record_marketing_event(
  p_session_id uuid,
  p_idempotency_key uuid,
  p_event_name text,
  p_campaign_id text,
  p_touchpoint_id text,
  p_content_type text,
  p_content_key text,
  p_path text,
  p_source text,
  p_properties jsonb,
  p_occurred_at timestamptz
)
returns table (event_id bigint, persisted boolean, received_at timestamptz)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_event_id bigint;
  v_received_at timestamptz;
  v_touchpoint_campaign text;
  v_property_count integer;
begin
  if v_user_id is null then
    raise exception using errcode = 'P0001', message = 'LOOM_AUTH_REQUIRED';
  end if;
  if p_event_name not in (
    'page_view', 'campaign_entry', 'cta_click', 'member_select', 'track_open',
    'vote_started', 'vote_saved', 'share_created', 'share_opened',
    'profile_saved', 'follow_changed', 'inquiry_started', 'inquiry_submitted',
    'membership_interest'
  ) then
    raise exception using errcode = 'P0001', message = 'LOOM_EVENT_INVALID';
  end if;
  if p_path is null or p_path !~ '^/' or char_length(p_path) > 500 or position('?' in p_path) > 0 then
    raise exception using errcode = 'P0001', message = 'LOOM_PATH_INVALID';
  end if;
  if p_path !~ '^/[A-Za-z0-9/_-]*$' then
    raise exception using errcode = 'P0001', message = 'LOOM_PATH_UNSAFE';
  end if;
  if p_content_key is not null and (
    char_length(p_content_key) not between 1 and 120
    or p_content_key !~ '^[A-Za-z0-9][A-Za-z0-9:_-]{0,119}$'
  ) then
    raise exception using errcode = 'P0001', message = 'LOOM_CONTENT_KEY_UNSAFE';
  end if;
  if p_properties is null or jsonb_typeof(p_properties) <> 'object' or pg_column_size(p_properties) > 4096 then
    raise exception using errcode = 'P0001', message = 'LOOM_PROPERTIES_INVALID';
  end if;
  select count(*) into v_property_count from jsonb_object_keys(p_properties);
  if v_property_count > 12 or exists (
    select 1
    from jsonb_each(p_properties) as property(key, value)
    where property.key not in (
      'medium', 'cta_position', 'state', 'inquiry_type', 'timeline',
      'follow_count', 'cross_device', 'option_key', 'vote_kind'
    )
      or property.key ~* '(email|name|phone|message|brief|content|token|secret|cookie|ip|address|user)'
      or jsonb_typeof(property.value) not in ('string', 'number', 'boolean', 'null')
      or (
        jsonb_typeof(property.value) = 'string'
        and coalesce(property.value #>> '{}', '') !~ '^[A-Za-z0-9][A-Za-z0-9_.:-]{0,79}$'
      )
  ) then
    raise exception using errcode = 'P0001', message = 'LOOM_PROPERTIES_UNSAFE';
  end if;
  if p_occurred_at < now() - interval '7 days' or p_occurred_at > now() + interval '5 minutes' then
    raise exception using errcode = 'P0001', message = 'LOOM_EVENT_TIME_INVALID';
  end if;

  if p_touchpoint_id is not null then
    select touchpoint.campaign_id
      into v_touchpoint_campaign
    from public.loom_campaign_touchpoints touchpoint
    where touchpoint.id = p_touchpoint_id
      and touchpoint.status in ('preview', 'active');

    if v_touchpoint_campaign is null then
      raise exception using errcode = 'P0001', message = 'LOOM_TOUCHPOINT_INVALID';
    end if;
    if p_campaign_id is distinct from v_touchpoint_campaign then
      raise exception using errcode = 'P0001', message = 'LOOM_CAMPAIGN_TOUCHPOINT_MISMATCH';
    end if;
  end if;

  insert into public.loom_marketing_events (
    user_id,
    session_id,
    idempotency_key,
    event_name,
    campaign_id,
    touchpoint_id,
    content_type,
    content_key,
    path,
    source,
    properties,
    occurred_at
  ) values (
    v_user_id,
    p_session_id,
    p_idempotency_key,
    p_event_name,
    p_campaign_id,
    p_touchpoint_id,
    p_content_type,
    p_content_key,
    p_path,
    p_source,
    p_properties,
    p_occurred_at
  )
  on conflict (user_id, idempotency_key) do nothing
  returning id, loom_marketing_events.received_at into v_event_id, v_received_at;

  if v_event_id is null then
    select event.id, event.received_at
      into v_event_id, v_received_at
    from public.loom_marketing_events event
    where event.user_id = v_user_id
      and event.idempotency_key = p_idempotency_key;

    return query select v_event_id, false, v_received_at;
    return;
  end if;

  return query select v_event_id, true, v_received_at;
end;
$$;

revoke all on function public.loom_record_marketing_event(uuid, uuid, text, text, text, text, text, text, text, jsonb, timestamptz) from public, anon, authenticated;
grant execute on function public.loom_record_marketing_event(uuid, uuid, text, text, text, text, text, text, text, jsonb, timestamptz) to authenticated;

create or replace function public.loom_save_fan_profile(
  p_favorite_member_code text,
  p_favorite_track_id text,
  p_locale text,
  p_cross_device_enabled boolean,
  p_follows jsonb,
  p_analytics_consent text,
  p_profile_sync_consent text,
  p_notifications_consent text,
  p_policy_version text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_follow jsonb;
  v_latest_profile_sync text;
  v_latest_notifications text;
begin
  if v_user_id is null then
    raise exception using errcode = 'P0001', message = 'LOOM_AUTH_REQUIRED';
  end if;
  if p_favorite_member_code is not null and p_favorite_member_code !~ '^M(0[1-9]|1[0-3])$' then
    raise exception using errcode = 'P0001', message = 'LOOM_MEMBER_INVALID';
  end if;
  if p_favorite_track_id is not null and (
    char_length(p_favorite_track_id) not between 1 and 120
    or p_favorite_track_id !~ '^[A-Za-z0-9][A-Za-z0-9:_-]{0,119}$'
  ) then
    raise exception using errcode = 'P0001', message = 'LOOM_TRACK_INVALID';
  end if;
  if p_locale !~ '^[a-z]{2}(-[A-Z]{2})?$' then
    raise exception using errcode = 'P0001', message = 'LOOM_LOCALE_INVALID';
  end if;
  if p_policy_version !~ '^loom-privacy-[0-9]{4}-[0-9]{2}$' then
    raise exception using errcode = 'P0001', message = 'LOOM_POLICY_INVALID';
  end if;
  if p_follows is null or jsonb_typeof(p_follows) <> 'array' or jsonb_array_length(p_follows) > 20 then
    raise exception using errcode = 'P0001', message = 'LOOM_FOLLOWS_INVALID';
  end if;

  for v_follow in select value from jsonb_array_elements(p_follows)
  loop
    if jsonb_typeof(v_follow) <> 'object'
      or coalesce(v_follow->>'subjectType', '') not in ('member', 'track', 'cf')
      or char_length(coalesce(v_follow->>'subjectKey', '')) not between 1 and 120
      or coalesce(v_follow->>'subjectKey', '') !~ '^[A-Za-z0-9][A-Za-z0-9:_-]{0,119}$'
      or jsonb_typeof(v_follow->'notificationsEnabled') <> 'boolean' then
      raise exception using errcode = 'P0001', message = 'LOOM_FOLLOW_INVALID';
    end if;
    if v_follow->>'subjectType' = 'member' and v_follow->>'subjectKey' !~ '^M(0[1-9]|1[0-3])$' then
      raise exception using errcode = 'P0001', message = 'LOOM_FOLLOW_MEMBER_INVALID';
    end if;
  end loop;

  if p_analytics_consent is not null then
    if p_analytics_consent not in ('granted', 'withdrawn') then
      raise exception using errcode = 'P0001', message = 'LOOM_CONSENT_INVALID';
    end if;
    if p_analytics_consent is distinct from (
      select consent.state from public.loom_marketing_consents consent
      where consent.user_id = v_user_id and consent.purpose = 'analytics'
      order by consent.occurred_at desc limit 1
    ) then
      insert into public.loom_marketing_consents (user_id, purpose, state, policy_version)
      values (v_user_id, 'analytics', p_analytics_consent, p_policy_version);
    end if;
  end if;

  if p_profile_sync_consent is not null then
    if p_profile_sync_consent not in ('granted', 'withdrawn') then
      raise exception using errcode = 'P0001', message = 'LOOM_CONSENT_INVALID';
    end if;
    if p_profile_sync_consent is distinct from (
      select consent.state from public.loom_marketing_consents consent
      where consent.user_id = v_user_id and consent.purpose = 'profile_sync'
      order by consent.occurred_at desc limit 1
    ) then
      insert into public.loom_marketing_consents (user_id, purpose, state, policy_version)
      values (v_user_id, 'profile_sync', p_profile_sync_consent, p_policy_version);
    end if;
  end if;

  if p_notifications_consent is not null then
    if p_notifications_consent not in ('granted', 'withdrawn') then
      raise exception using errcode = 'P0001', message = 'LOOM_CONSENT_INVALID';
    end if;
    if p_notifications_consent is distinct from (
      select consent.state from public.loom_marketing_consents consent
      where consent.user_id = v_user_id and consent.purpose = 'notifications'
      order by consent.occurred_at desc limit 1
    ) then
      insert into public.loom_marketing_consents (user_id, purpose, state, policy_version)
      values (v_user_id, 'notifications', p_notifications_consent, p_policy_version);
    end if;
  end if;

  select consent.state
    into v_latest_profile_sync
  from public.loom_marketing_consents consent
  where consent.user_id = v_user_id and consent.purpose = 'profile_sync'
  order by consent.occurred_at desc
  limit 1;

  if p_cross_device_enabled and v_latest_profile_sync is distinct from 'granted' then
    raise exception using errcode = 'P0001', message = 'LOOM_PROFILE_SYNC_CONSENT_REQUIRED';
  end if;

  select consent.state
    into v_latest_notifications
  from public.loom_marketing_consents consent
  where consent.user_id = v_user_id and consent.purpose = 'notifications'
  order by consent.occurred_at desc
  limit 1;

  if exists (
    select 1 from jsonb_array_elements(p_follows) follow
    where (follow->>'notificationsEnabled')::boolean = true
  ) and v_latest_notifications is distinct from 'granted' then
    raise exception using errcode = 'P0001', message = 'LOOM_NOTIFICATION_CONSENT_REQUIRED';
  end if;

  insert into public.loom_fan_profiles (
    user_id, favorite_member_code, favorite_track_id, locale, cross_device_enabled
  ) values (
    v_user_id, p_favorite_member_code, p_favorite_track_id, p_locale, p_cross_device_enabled
  )
  on conflict (user_id) do update
    set favorite_member_code = excluded.favorite_member_code,
        favorite_track_id = excluded.favorite_track_id,
        locale = excluded.locale,
        cross_device_enabled = excluded.cross_device_enabled,
        profile_version = loom_fan_profiles.profile_version + 1;

  delete from public.loom_follows where user_id = v_user_id;

  insert into public.loom_follows (user_id, subject_type, subject_key, notifications_enabled)
  select
    v_user_id,
    follow."subjectType",
    follow."subjectKey",
    follow."notificationsEnabled"
  from jsonb_to_recordset(p_follows) as follow(
    "subjectType" text,
    "subjectKey" text,
    "notificationsEnabled" boolean
  );

  return jsonb_build_object(
    'saved', true,
    'followCount', jsonb_array_length(p_follows),
    'crossDeviceEnabled', p_cross_device_enabled
  );
end;
$$;

